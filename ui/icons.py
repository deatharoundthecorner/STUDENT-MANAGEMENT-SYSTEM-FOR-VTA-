def render_svg_pixmap(name: str, color: str = "#64748B", stroke_width: float = 1.8, size: int = 24) -> QPixmap:
    """Renders a vector icon from ICON_PATHS directly to a high-DPI transparent QPixmap."""
    path_data = ICON_PATHS.get(name)
    if not path_data:
        pix = QPixmap(size, size)
        pix.fill(Qt.transparent)
        return pix

    svg_str = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round">{path_data}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))
    pix = QPixmap(size, size)
    pix.fill(Qt.transparent)
    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()
    return pix

def get_icon(name: str, color: str = "#64748B", active_color: str = None, disabled_color: str = "#94A3B8", size: int = 20) -> QIcon:
    """Returns a multi-state QIcon from a vector SVG path with designated color tokens."""
    icon = QIcon()
    normal_pix = render_svg_pixmap(name, color=color, stroke_width=1.8, size=size * 2)
    icon.addPixmap(normal_pix, QIcon.Normal, QIcon.Off)

    if active_color:
        active_pix = render_svg_pixmap(name, color=active_color, stroke_width=2.0, size=size * 2)
        icon.addPixmap(active_pix, QIcon.Active, QIcon.Off)
        icon.addPixmap(active_pix, QIcon.Normal, QIcon.On)
    else:
        icon.addPixmap(normal_pix, QIcon.Normal, QIcon.On)

    if disabled_color:
        dis_pix = render_svg_pixmap(name, color=disabled_color, stroke_width=1.5, size=size * 2)
        icon.addPixmap(dis_pix, QIcon.Disabled, QIcon.Off)

    return icon

def get_pixmap(name: str, color: str = "#0D9488", stroke_width: float = 1.8, size: int = 24) -> QPixmap:
    """Convenience helper returning a QPixmap directly."""
    return render_svg_pixmap(name, color=color, stroke_width=stroke_width, size=size)
